export function PixelIcon({
  name,
  size = 20,
  color,
}: {
  name: string
  size?: number
  color?: string
}) {
  const rows = BITMAPS[name] ?? BITMAPS.key
  const grid = rows.length
  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${grid} ${grid}`}
      shapeRendering="crispEdges"
      style={{ flexShrink: 0 }}
      aria-hidden="true"
    >
      {rows.map((row, y) =>
        row
          .padEnd(grid, '.')
          .slice(0, grid)
          .split('')
          .map((ch, x) =>
            ch === '#' ? (
              <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={color ?? 'currentColor'} />
            ) : null,
          ),
      )}
    </svg>
  )
}
